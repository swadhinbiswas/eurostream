    @app.get(
        "/stream/alerts",
        tags=["pipeline"],
        summary="Live fraud alerts as Server-Sent Events",
        response_class=StreamingResponse,
        responses={
            200: {
                "description": (
                    "`text/event-stream` of fraud alerts as they are scored. "
                    "Each frame carries `id` (the resume point), `event: alert` "
                    "and a JSON `data` payload. A `: ping` comment is emitted "
                    "every `heartbeat` seconds so proxies keep the connection open."
                ),
                "content": {"text/event-stream": {}},
            },
        },
    )
    def stream_alerts(
        since: int | None = Query(
            default=None,
            ge=0,
            description=(
                "Replay buffered alerts after this event id. Defaults to the "
                "standard `Last-Event-ID` header (browsers send it on reconnect); "
                "with neither, the stream starts live."
            ),
        ),
        last_event_id: Annotated[
            str | None,
            Header(alias="Last-Event-ID", description="Event id of the last frame this client saw"),
        ] = None,
        heartbeat: float = Query(
            default=15.0, ge=0.1, le=60.0, description="Seconds between `: ping` comments"
        ),
        duration: float | None = Query(
            default=None,
            ge=0.0,
            le=3600.0,
            description="Close the stream after this many seconds (omit to stream until disconnect)",
        ),
    ) -> StreamingResponse:
        """Server-Sent Events feed of fraud alerts scored by `POST /stream`.

        Reconnecting clients resume without a gap: send `Last-Event-ID` (or
        `?since=`) and the buffered events after it are replayed before the
        live tail.
        """
        resume = since if since is not None else parse_last_event_id(last_event_id)
        # Only a client that states a resume point gets history back; a fresh
        # browser tab should not be flooded with the buffer.
        replay_history = since is not None or last_event_id is not None
        metrics.incr("alert_streams_opened")
        served = 0

        def events() -> Iterator[str]:
            nonlocal served
            subscriber, snapshot = broker.subscribe()
            cursor = resume
            started = time.monotonic()
            try:
                # Tell the browser how quickly to reconnect if we drop.
                yield "retry: 3000\n\n"
                if replay_history:
                    for seq, payload in snapshot:
                        if seq > cursor:
                            yield format_event(seq, payload)
                            cursor = seq
                            served += 1
                while True:
                    elapsed = time.monotonic() - started
                    if duration is not None and elapsed >= duration:
                        return
                    timeout = heartbeat
                    if duration is not None:
                        timeout = max(0.05, min(heartbeat, duration - elapsed))
                    try:
                        seq, payload = subscriber.get(timeout=timeout)
                    except queue.Empty:
                        yield ": ping\n\n"
                        continue
                    if seq <= cursor:
                        continue
                    yield format_event(seq, payload)
                    cursor = seq
                    served += 1
            finally:
                # Runs on disconnect too: never leak a subscriber queue.
                broker.unsubscribe(subscriber)
                metrics.incr("alert_stream_events", served)

        return StreamingResponse(
            events(),
            media_type="text/event-stream",
            headers={
                "Cache-Control": "no-cache",
                "X-Accel-Buffering": "no",
                "Connection": "keep-alive",
            },
        )

    @app.post(
        "/transform",
        tags=["pipeline"],
        summary="Run the medallion DAG (bronze -> silver -> gold -> lake)",
        dependencies=[Depends(require_token), Depends(rate_limit)],
        responses={
            503: {"description": "Bus or warehouse is not wired into this server"},
            500: {"description": "A DAG task failed; the response names the failing task"},
        },
    )
    def trigger_transform(
        incremental: bool = Query(default=True, description="Watermark-based incremental build"),
    ) -> Any:
        """Runs the Medallion transformation pipeline DAG and updates Lake."""
        if bus is None or warehouse is None:
            return service_unavailable("event bus or warehouse is not wired into this server")
        lineage = LineageEmitter(settings.data_dir / "lineage.jsonl")
        classifier = PIIClassifier(settings.pii_manifest_path)

        def ingest_bronze() -> None:
            lineage.start(
                "ingest_bronze",
                inputs=["bus.orders", "bus.clicks", "bus.payments"],
                outputs=["bronze.orders", "bronze.clicks", "bronze.payments"],
            )
            loaded = {}
            for topic in ("orders", "clicks", "payments"):
                consumer = bus.consumer(topic, "api-bronze-ingest", auto_offset_reset="earliest")
                records = []
                while True:
                    rec = consumer.poll(0.05)
                    if rec is None:
                        break
                    records.append(rec)
                    if len(records) >= 1000:
                        break
                if records:
                    warehouse.load_bronze_from_records(topic, records)
                    consumer.commit()
                loaded[topic] = len(records)
                consumer.close()
            lineage.complete("ingest_bronze", extra=loaded)

        def pii_scan() -> None:
            rows = warehouse.bronze_rows("orders", 200)
            for r in rows:
                r["_table"] = "bronze.orders"
            manifest = classifier.load()
            if not manifest:
                classifier.build_from_rows(rows)
                classifier.save()
                warehouse.save_manifest(classifier.load())
                return
            findings = classifier.detect_unregistered(rows)
            if findings:
                raise RuntimeError(f"unregistered PII columns: {findings}")

        def build_silver() -> None:
            lineage.start(
                "build_silver",
                inputs=["bronze.orders", "bronze.payments"],
                outputs=["silver.customers", "silver.orders", "silver.payments"],
            )
            if incremental:
                stats = warehouse.build_silver_incremental(pii_salt=settings.pii_salt)
                lineage.complete("build_silver", extra=stats)
            else:
                warehouse.build_silver(pii_salt=settings.pii_salt)
                lineage.complete("build_silver")

        def build_gold() -> None:
            lineage.start(
                "build_gold",
                inputs=["silver.customers", "silver.orders"],
                outputs=["gold.customer_360", "gold.order_facts"],
            )
            if incremental:
                stats = warehouse.build_gold_incremental()
                lineage.complete("build_gold", extra=stats)
            else:
                warehouse.build_gold()
                lineage.complete("build_gold")

        def quality_gate() -> None:
            report = DataQualityEngine(warehouse).run_all()
            if not report.all_passed:
                failed = [r.check_name for r in report.results if not r.passed]
                raise RuntimeError(f"data quality gate failed: {failed}")

        def export_lake() -> None:
            warehouse.export_lake(settings.lake_root)

        dag = DAG(
            dag_id="medallion-api",
            tasks=[
                DAGTask("ingest_bronze", ingest_bronze, depends_on=[]),
                DAGTask("pii_scan", pii_scan, depends_on=["ingest_bronze"]),
                DAGTask("build_silver", build_silver, depends_on=["pii_scan"]),
                DAGTask("build_gold", build_gold, depends_on=["build_silver"]),
                DAGTask("quality_gate", quality_gate, depends_on=["build_gold"]),
                DAGTask("export_lake", export_lake, depends_on=["quality_gate"]),
            ],
        )
        results = dag.run()
        metrics.flush()
        return {
            "status": "ok",
            "incremental": incremental,
            "tasks": {
                k: {"ok": v.ok, "duration_s": round(v.duration_s, 3)} for k, v in results.items()
            },
        }

