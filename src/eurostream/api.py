    @app.get("/health/ready", tags=["meta"], summary="Readiness probe")
    def health_ready(response: JSONResponse) -> Any:
        """503 until the warehouse answers, so a load balancer stops sending
        traffic to a process whose database is gone."""
        checks: dict[str, str] = {"warehouse": "ok", "bus": "ok"}
        if warehouse is None:
            checks["warehouse"] = "not_configured"
        else:
            try:
                warehouse.scalar("SELECT 1", local_only=True)
            except Exception as e:  # pragma: no cover - only on a broken DB
                checks["warehouse"] = f"error: {e}"
        if bus is None:
            checks["bus"] = "not_configured"
        ready = not any(v.startswith("error") for v in checks.values())
        if not ready:
            response.status_code = 503
        return {"status": "ready" if ready else "not_ready", "checks": checks}

