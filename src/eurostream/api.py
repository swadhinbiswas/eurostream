def _pending_item(entry: dict[str, object]) -> dict[str, object]:
    """Shape an intake entry like an audit row, with the absent fields null."""
    requested_at = entry.get("requested_at")
    return {
        "request_id": entry.get("request_id"),
        "customer_id": entry.get("customer_id"),
        "status": entry.get("status"),
        "requested_at": requested_at if isinstance(requested_at, (int, float)) else None,
        "completed_at": None,
        "duration_seconds": None,
        "layers_touched": [],
        "confirmation_hash": None,
        "requested_by": entry.get("requested_by"),
    }


def _audit_item(row: dict[str, object]) -> dict[str, object]:
    """Shape an audit-log row for the API (duration derived, layers split)."""
    requested_at = row.get("requested_at")
    completed_at = row.get("completed_at")
    requested = float(requested_at) if isinstance(requested_at, (int, float)) else None
    completed = float(completed_at) if isinstance(completed_at, (int, float)) else None
    layers = [layer for layer in str(row.get("layers_touched") or "").split(",") if layer]
    duration = (
        round(completed - requested, 3) if requested is not None and completed is not None else None
    )
    return {
        "request_id": row.get("request_id"),
        "customer_id": row.get("customer_id"),
        "status": row.get("status"),
        "requested_at": requested,
        "completed_at": completed,
        "duration_seconds": duration,
        "layers_touched": layers,
        "confirmation_hash": row.get("confirmation_hash"),
        "requested_by": None,
    }


def _requested_ts(item: dict[str, object]) -> float:
    """Sort key for request timestamps; missing/odd values sort oldest."""
    value = item.get("requested_at")
    return float(value) if isinstance(value, (int, float)) else 0.0


def _bus_backend(bus: Any) -> str:
    """Report the backend actually in use, not the one that was requested."""
    if bus is None:
        return "none"
    return "kafka" if type(bus).__module__.endswith(".bus.kafka") else "sqlite"


def create_app(
    erasure: ErasureService,
    metrics: Metrics,
    settings: Settings,
    warehouse: Warehouse | None = None,
    bus: Any = None,
    *,
    backend: str | None = None,
    start_worker: bool = True,
    api_token: str | None = None,
) -> FastAPI:
    """Build the FastAPI app.

    ``backend`` overrides the detected event-bus backend (used when the bus
    proxy hides its concrete type). ``start_worker`` runs the erasure consumer
    as a lifespan thread so queued Art. 17 requests actually execute — without
    it the ``/erasure-requests`` endpoint would only pretend to enqueue.
    ``api_token`` locks down the mutating routes when set (via
    ``EUROSTREAM_API_TOKEN``).
    """
    effective_backend = backend or _bus_backend(bus)
    requested_backend = settings.event_bus_backend
    # Live alert fan-out for GET /stream/alerts (see eurostream.alerts).
    broker = AlertBroker()

    def publish_alert(alert: FraudAlert) -> None:
        broker.publish(alert.to_dict())

    # One processor, one consumer group, one owner. Two consumers in a group
    # would each score every payment and land duplicate alerts; the lock makes
    # the background loop and POST /stream take turns on the same consumer.
    fraud_processor: FraudStreamProcessor | None = None
    if bus is not None and warehouse is not None:
        fraud_processor = FraudStreamProcessor(
            consumer=bus.consumer(
                "payments", settings.fraud_consumer_group, auto_offset_reset="earliest"
            ),
            scorer=FraudScorer(settings, metrics),
            metrics=metrics,
            output_producer=bus,
            alert_topic="fraud_alerts",
            suppression_check=erasure.is_suppressed,
            on_alert=publish_alert,
        )
    fraud_lock = threading.Lock()
    # Filled in by the lifespan; /stats reports liveness from the threads
    # themselves rather than from what the configuration says should happen.
    workers: dict[str, threading.Thread | None] = {"erasure": None, "fraud": None}
    # Retry safety for the one endpoint that deletes data (see idempotency.py).
    idempotency = IdempotencyStore()
    # Per-client pacing for the routes that change state (see ratelimit.py).
    limiter = RateLimiter(settings.api_rate_limit, settings.api_rate_limit_burst)
    # Format every EuroStream line the way this deployment wants it before the
    # first log fires (lifespan, worker, request handlers).
    configure_logging(settings.log_level, settings.log_format)
    degraded = effective_backend != requested_backend
    if degraded:
        logger.warning(
            "event bus degraded: requested=%s effective=%s",
            requested_backend,
            effective_backend,
        )

    @asynccontextmanager
    async def lifespan(_: FastAPI) -> AsyncIterator[None]:
        stop = threading.Event()
        worker: threading.Thread | None = None
        fraud_worker: threading.Thread | None = None

        def fraud_loop() -> None:
            """Drain the payments topic until shutdown.

            `run()` returns after a short idle stretch, which is the loop's
            natural tick: ingest what arrived, then wait to be woken. Alerts
            are ingested while the fraud lock is held so a `POST /stream`
            cannot interleave two alert sets into bronze.
            """
            assert fraud_processor is not None and warehouse is not None
            while not stop.is_set():
                with fraud_lock:
                    alerts = fraud_processor.run(poll_timeout=0.2, idle_stop=5)
                    if alerts:
                        warehouse.ingest_fraud_alerts([a.to_dict() for a in alerts])
                if alerts:
                    metrics.flush()
                stop.wait(0.5)

        if start_worker and bus is not None:
            worker = threading.Thread(
                target=erasure.run_worker,
                kwargs={"poll_timeout": 0.2, "stop_event": stop},
                name="eurostream-erasure-worker",
                daemon=True,
            )
            worker.start()
            workers["erasure"] = worker
            logger.info("erasure worker running in background")
        if (
            start_worker
            and settings.fraud_worker_enabled
            and fraud_processor is not None
            and warehouse is not None
        ):
            fraud_worker = threading.Thread(
                target=fraud_loop,
                name="eurostream-fraud-worker",
                daemon=True,
            )
            fraud_worker.start()
            workers["fraud"] = fraud_worker
            logger.info(
                "fraud scoring worker running in background (group=%s)",
                settings.fraud_consumer_group,
            )
        try:
            yield
        finally:
            stop.set()
            if fraud_processor is not None:
                # Unblocks a poll mid-drain; the processor is not reused.
                fraud_processor.stop()
            if worker is not None:
                worker.join(timeout=5)
            if fraud_worker is not None:
                fraud_worker.join(timeout=5)
            metrics.flush()
            logger.info("shutdown complete: metrics flushed")

    app = FastAPI(
        title="EuroStream Governance API",
        version=__version__,
        description=(
            "GDPR-compliant real-time customer analytics, DSAR right-to-erasure "
            "cascade, and Prometheus observability."
        ),
        lifespan=lifespan,
        contact={"name": "EuroStream", "url": "https://github.com/swadhinbiswas/eurostream"},
        license_info={"name": "MIT"},
        servers=[{"url": "/", "description": "This server"}],
    )
    # Exposed for the dashboard/tests: publish an alert and watch it leave
    # through GET /stream/alerts.
    app.state.alert_broker = broker

    origins = [o.strip() for o in settings.cors_origins.split(",") if o.strip()]
    wildcard = "*" in origins
    app.add_middleware(
        CORSMiddleware,
        allow_origins=origins,
        # Credentialed CORS is only safe with an explicit origin allowlist.
        allow_credentials=not wildcard,
        allow_methods=["GET", "POST", "OPTIONS"],
        allow_headers=["Content-Type", "X-Request-ID", "Idempotency-Key"]
        + (["Authorization"] if api_token else []),
        expose_headers=[REQUEST_ID_HEADER, "Idempotent-Replay"],
    )

    @app.middleware("http")
    async def request_id_middleware(request: Request, call_next: Any) -> Any:
        rid = request.headers.get(REQUEST_ID_HEADER) or uuid.uuid4().hex
        request.state.request_id = rid
        # Bind the correlation id for everything logged while this request is
        # in scope — including the sync endpoints running on worker threads.
        token = set_request_id(rid)
        try:
            started = time.perf_counter()
            response = await call_next(request)
            elapsed = time.perf_counter() - started
        finally:
            reset_request_id(token)
        response.headers[REQUEST_ID_HEADER] = rid

        # Label by the *route template* (from the matched route, not the raw
        # URL) so an attacker cannot blow up the metrics cardinality with
        # arbitrary path segments.
        route = request.scope.get("route")
        path_label = getattr(route, "path", None) or "/"
        metrics.observe("http_request_duration_seconds", elapsed)
        metrics.record_request(response.status_code)
        metrics.incr(
            "http_requests_total",
            labels={
                "method": request.method,
                "path": path_label,
                "status": str(response.status_code),
            },
        )
        # Structured access line: the request id in this record matches the
        # response header and every log line emitted while handling it. It is
        # passed explicitly because this line runs after the scope is reset.
        logger.info(
            "%s %s -> %s",
            request.method,
            path_label,
            response.status_code,
            extra={
                "request_id": rid,
                "method": request.method,
                "path": path_label,
                "status": response.status_code,
                "duration_ms": round(elapsed * 1000, 3),
            },
        )
        return response

    @app.exception_handler(StarletteHTTPException)
    async def http_exception_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
        detail = exc.detail if isinstance(exc.detail, str) else str(exc.detail)
        return problem(
            exc.status_code,
            _status_title(exc.status_code),
            detail,
            headers=dict(getattr(exc, "headers", None) or {}),
        )

    @app.exception_handler(RequestValidationError)
    async def validation_exception_handler(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        problems = []
        for err in exc.errors():
            loc = ".".join(str(p) for p in err.get("loc", ()) if p != "body")
            problems.append(f"{loc}: {err.get('msg', 'invalid')}")
        return problem(
            422,
            "Validation error",
            "; ".join(problems) or "request body failed validation",
        )

    @app.exception_handler(Exception)
    async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
        rid = getattr(request.state, "request_id", "-")
        logger.exception("unhandled error [%s] on %s %s", rid, request.method, request.url.path)
        return problem(
            500,
            "Internal server error",
            f"unexpected failure (request id {rid})",
        )

    def rate_limit(request: Request) -> None:
        """Per-client token bucket on mutating routes; 429 problem+json.

        The key is the first hop of X-Forwarded-For when present (the
        platform runs behind a proxy in every deployment that matters) and
        the socket address otherwise.
        """
        if not limiter.enabled:
            return
        client = request.client.host if request.client else "unknown"
        forwarded = request.headers.get("X-Forwarded-For", "")
        if forwarded:
            client = forwarded.split(",")[0].strip() or client
        allowed, retry_after = limiter.check(client)
        if not allowed:
            metrics.incr("rate_limited_requests")
            retry = max(1, int(math.ceil(retry_after)))
            raise HTTPException(
                status_code=429,
                detail=f"rate limit exceeded for {client}; retry in {retry}s",
                headers={"Retry-After": str(retry)},
            )

    def require_token(request: Request) -> None:
        if not api_token:
            return
        supplied = request.headers.get("Authorization", "").removeprefix("Bearer ").strip()
        if supplied != api_token:
            raise HTTPException(
                status_code=401,
                detail="missing or invalid bearer token",
                headers={"WWW-Authenticate": "Bearer"},
            )

