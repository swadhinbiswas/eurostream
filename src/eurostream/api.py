def problem(
    status: int,
    title: str,
    detail: str,
    *,
    type_uri: str = "about:blank",
    headers: dict[str, str] | None = None,
) -> JSONResponse:
    """RFC 9457 problem+json — one error shape for every failure the API returns."""
    body: dict[str, object] = {
        "type": type_uri,
        "title": title,
        "status": status,
        "detail": detail,
    }
    return JSONResponse(
        status_code=status,
        content=body,
        media_type=PROBLEM_MEDIA_TYPE,
        headers=headers,
    )


def service_unavailable(detail: str) -> JSONResponse:
    """A dependency (bus/warehouse) is not wired up, so the route cannot run."""
    return problem(
        503,
        "Service unavailable",
        detail,
        type_uri="https://eurostream.dev/problems/service-unavailable",
    )


