class _LakeFallback:
    """Row counts from the public Hugging Face Parquet lake, cached.

    The dashboard polls ``/stats`` every few seconds and a cold ``hf://``
    read costs seconds per table, so an uncached fallback would make a fresh
    deployment feel permanently hung. Negative results are cached too.
    """

    _TTL_SECONDS = 300.0

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self._repo: str | None = None
        self._at = 0.0
        self._stats: dict[str, int] = {}
        self._populated = False

    def get(self, repo: str) -> dict[str, int]:
        with self._lock:
            if (
                self._populated
                and self._repo == repo
                and time.time() - self._at < self._TTL_SECONDS
            ):
                return dict(self._stats)
        stats = self._fetch(repo)
        with self._lock:
            self._repo = repo
            self._at = time.time()
            self._stats = stats
            self._populated = True
        return dict(stats)

    @staticmethod
    def _fetch(repo: str) -> dict[str, int]:
        tables = (
            ("silver/orders", "silver_customers"),
            ("gold/customer_360", "gold_customers"),
            ("gold/order_facts", "gold_order_facts"),
            ("gold/fraud_summary", "fraud_alerts"),
        )
        out: dict[str, int] = {}
        cleaned = repo.strip().strip("\"' \t\r\n")
        if not cleaned or not all(c.isalnum() or c in "-_./" for c in cleaned):
            logger.warning("refusing lake fallback for unsafe repo id %r", repo)
            return out
        try:
            import duckdb

            hf_base = f"hf://datasets/{cleaned}"
            for tbl, key in tables:
                try:
                    row = duckdb.query(
                        f"SELECT count(*) FROM read_parquet('{hf_base}/{tbl}.parquet')"  # noqa: S608
                    ).fetchone()
                    if row and row[0]:
                        out[key] = int(row[0])
                except Exception as e:
                    logger.debug("lake fallback %s failed: %s", tbl, e)
        except Exception as e:
            logger.warning("HF lake fallback unavailable: %s", e)
        return out


_LAKE_FALLBACK = _LakeFallback()


